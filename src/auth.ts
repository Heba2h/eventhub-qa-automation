import fs from 'node:fs';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { env } from '@config';
import { createApiContext } from '@api/client';
import { AuthApi } from '@api/EventHubApi';
import type { Credentials } from '@api/models';

// ---------------------------------------------------------------------------------------------
// Roles
// ---------------------------------------------------------------------------------------------

/**
 * Identities the framework can authenticate as.
 * To add a role (e.g. "admin"), add it here with its env variable names — setup, fixtures,
 * cleanup and storage states pick it up automatically.
 */
export const USER_ROLES = {
  primary: { emailVar: 'EVENTHUB_USER_EMAIL', passwordVar: 'EVENTHUB_USER_PASSWORD' },
  secondary: { emailVar: 'EVENTHUB_SECONDARY_EMAIL', passwordVar: 'EVENTHUB_SECONDARY_PASSWORD' },
} as const;

export type UserRole = keyof typeof USER_ROLES;

/** `anonymous` = no token at all; used to verify that protected resources really are protected. */
export type Role = UserRole | 'anonymous';

export const ALL_USER_ROLES = Object.keys(USER_ROLES) as UserRole[];

/** localStorage key the EventHub web app reads its JWT from. */
export const TOKEN_STORAGE_KEY = 'eventhub_token';

// ---------------------------------------------------------------------------------------------
// Session
// ---------------------------------------------------------------------------------------------

/**
 * Everything about obtaining and storing a logged-in session:
 *   1. resolve credentials  (.env / CI secrets -> cached generated account -> register a new one)
 *   2. log in and verify the token
 *   3. persist it for API clients (token) and for browsers (storage state)
 * `authenticate()` is the ONLY place in the framework that performs a login.
 */

export interface StoredSession {
  role: UserRole;
  email: string;
  userId: number;
  token: string;
}

type CredentialSource = 'env' | 'cache';

const credentialsCacheFile = (role: UserRole) => path.join(env.authDir, `${role}.credentials.json`);
const sessionFile = (role: UserRole) => path.join(env.authDir, `${role}.session.json`);

/** Playwright storage state consumed by browser contexts (`use.storageState`). */
export const storageStatePath = (role: UserRole) => path.join(env.authDir, `${role}.storage-state.json`);

// ---------------------------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------------------------

export async function authenticate(role: UserRole): Promise<StoredSession> {
  const anonymous = await createApiContext();
  try {
    const auth = new AuthApi(anonymous);
    const { credentials, token } = await obtainToken(role, auth);
    const userId = await verifyToken(token);
    const session: StoredSession = { role, email: credentials.email, userId, token };
    saveSession(session);
    return session;
  } finally {
    await anonymous.dispose();
  }
}

export function loadSession(role: UserRole): StoredSession {
  const file = sessionFile(role);
  if (!fs.existsSync(file)) {
    throw new Error(
      `No session for role "${role}" at ${file}. Sessions are created by the "setup" project — ` +
        `run tests through a project that depends on it (e.g. --project=api or --project=ui-chromium).`,
    );
  }
  return JSON.parse(fs.readFileSync(file, 'utf8')) as StoredSession;
}

// ---------------------------------------------------------------------------------------------
// Credentials
// ---------------------------------------------------------------------------------------------

/**
 * Resolution order for a role's credentials:
 *  1. Environment variables (.env locally, repository secrets in CI) — the normal path.
 *  2. Credentials generated by a previous run on this machine (.auth/ cache) — avoids creating
 *     a new account on every local run against the shared public environment.
 *  3. `null` -> the caller registers a fresh account.
 */
function resolveConfiguredCredentials(role: UserRole): (Credentials & { source: CredentialSource }) | null {
  const { emailVar, passwordVar } = USER_ROLES[role];
  const email = process.env[emailVar]?.trim();
  const password = process.env[passwordVar]?.trim();

  if (email && password) return { email, password, source: 'env' };
  if (email || password) {
    throw new Error(`Set both ${emailVar} and ${passwordVar}, or neither (to auto-register a user).`);
  }

  const file = credentialsCacheFile(role);
  if (fs.existsSync(file)) {
    const cached = JSON.parse(fs.readFileSync(file, 'utf8')) as Credentials;
    return { ...cached, source: 'cache' };
  }
  return null;
}

async function obtainToken(role: UserRole, auth: AuthApi): Promise<{ credentials: Credentials; token: string }> {
  const configured = resolveConfiguredCredentials(role);
  if (!configured) return registerNew(role, auth);

  const login = await auth.login(configured);
  if (login.status === 200) return { credentials: configured, token: login.body.token };

  if (configured.source === 'env') {
    throw new Error(
      `Login failed for role "${role}" (${configured.email}) with HTTP ${login.status}: ` +
        `${JSON.stringify(login.body)}. Check the credentials in .env / CI secrets.`,
    );
  }
  // A previously generated account is no longer valid (e.g. environment was reset) — start over.
  fs.rmSync(credentialsCacheFile(role), { force: true });
  return registerNew(role, auth);
}

async function registerNew(role: UserRole, auth: AuthApi) {
  const suffix = `${Date.now().toString(36)}${randomBytes(3).toString('hex')}`;
  const credentials: Credentials = {
    email: `eventhub.qa.${role}.${suffix}@example.com`,
    password: `Qa!${randomBytes(9).toString('base64url')}`,
  };
  const token = (await auth.register(credentials)).expectStatus(201).token;

  fs.mkdirSync(env.authDir, { recursive: true });
  fs.writeFileSync(credentialsCacheFile(role), JSON.stringify(credentials, null, 2));
  return { credentials, token };
}

/** Validates the token against /auth/me so a broken session fails once in setup, not in every test. */
async function verifyToken(token: string): Promise<number> {
  const context = await createApiContext(token);
  try {
    return (await new AuthApi(context).me()).expectStatus(200).user.userId;
  } finally {
    await context.dispose();
  }
}

// ---------------------------------------------------------------------------------------------
// Persistence
// ---------------------------------------------------------------------------------------------

/**
 * Persists a session in the two shapes the framework needs:
 *  - `<role>.session.json`        -> token + identity for API clients
 *  - `<role>.storage-state.json`  -> browser storage state, so UI tests start already logged in
 *                                    (the app keeps its JWT in localStorage)
 */
function saveSession(session: StoredSession): void {
  fs.mkdirSync(env.authDir, { recursive: true });
  fs.writeFileSync(sessionFile(session.role), JSON.stringify(session, null, 2));
  const storageState = {
    cookies: [],
    origins: [{ origin: env.baseUrl, localStorage: [{ name: TOKEN_STORAGE_KEY, value: session.token }] }],
  };
  fs.writeFileSync(storageStatePath(session.role), JSON.stringify(storageState, null, 2));
}
